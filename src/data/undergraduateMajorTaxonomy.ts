export const recommendedUndergraduateMajorCategories = Object.values(
  undergraduateMajorCategoryLabels,
).filter((label, index, values) => values.indexOf(label) === index).sort((first, second) => first.localeCompare(second, "zh-CN"));

export function formatUndergraduateMajorCategory(category: string): string {
  const normalized = category.trim();
  return undergraduateMajorCategoryLabels[normalized] ?? normalized.replace(/-/g, " ");
}
